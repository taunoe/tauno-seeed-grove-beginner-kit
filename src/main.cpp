// --- UTILITY FUNCTIONS ---
int filter_sound(int newData, int queue[], int len) {
  int max_val = newData;
  int min_val = newData;
  long sum = newData;
  for (int i = len - 1; i > 0; i--) {
    queue[i] = queue[i - 1];
    if (queue[i] > max_val) max_val = queue[i];
    if (queue[i] < min_val) min_val = queue[i];
    sum += queue[i];
  }
  queue[0] = newData;
  if (len > 2) {
    sum = sum - max_val - min_val;
    return sum / (len - 2);
  } else {
    return sum / len;
  }
}
